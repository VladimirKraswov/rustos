//! Минимальный встроенный 5x7 bitmap-font.
//!
//! Шрифт намеренно хранится кодом: ранняя GUI-сессия не зависит от файловой
//! системы и может показать диагностику даже при повреждённом initramfs.

use crate::graphics::{Color, Framebuffer};

pub const GLYPH_WIDTH: i32 = 6;
pub const GLYPH_HEIGHT: i32 = 8;

pub fn draw_char(fb: &mut Framebuffer, x: i32, y: i32, character: u8, color: Color, scale: u32) {
    let rows = glyph(character.to_ascii_uppercase());
    let scale = scale.max(1) as i32;
    for (row, bits) in rows.iter().copied().enumerate() {
        for column in 0..5 {
            if bits & (1 << (4 - column)) != 0 {
                for sy in 0..scale {
                    for sx in 0..scale {
                        fb.put_pixel(x + column * scale + sx, y + row as i32 * scale + sy, color);
                    }
                }
            }
        }
    }
}

pub fn draw_text(fb: &mut Framebuffer, mut x: i32, y: i32, text: &str, color: Color, scale: u32) {
    let advance = GLYPH_WIDTH * scale.max(1) as i32;
    for byte in text.bytes() {
        draw_char(fb, x, y, byte, color, scale);
        x += advance;
    }
}

